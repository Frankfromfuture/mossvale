import {spawn} from 'node:child_process';
import path from 'node:path';
import {existsSync} from 'node:fs';
const root=path.resolve(import.meta.dirname,'..');
const brizo=process.env.BRIZO_ROOT||path.resolve(root,'../Brizo');
const electron=path.join(brizo,'node_modules/electron/dist/Electron.app/Contents/MacOS/Electron');
const useBrizo=process.platform==='darwin'&&existsSync(electron)&&!process.env.MOSSVALE_RULES_ONLY&&!process.env.DEEPSEEK_API_KEY;
const env={...process.env,BRIZO_ROOT:brizo};delete env.ELECTRON_RUN_AS_NODE;
const child=spawn(useBrizo?electron:process.execPath,[path.join(root,'server',useBrizo?'brizo-entry.mjs':'main.mjs')],{cwd:root,env,stdio:'inherit'});
for(const sig of ['SIGINT','SIGTERM'])process.on(sig,()=>child.kill(sig));
child.on('exit',code=>process.exit(code||0));
